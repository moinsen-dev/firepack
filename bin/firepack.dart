import 'dart:io';

import 'package:args/command_runner.dart';
import 'package:firepack/firepack.dart';
import 'package:watcher/watcher.dart';
import 'package:yaml/yaml.dart';

Future<void> main(List<String> args) async {
  final runner = CommandRunner<int>(
    'firepack',
    'Spec-driven Firestore + Flutter codegen.',
  )
    ..addCommand(_LintCommand())
    ..addCommand(_VizCommand())
    ..addCommand(_RegenCommand())
    ..addCommand(_DiffCommand())
    ..addCommand(_WatchCommand());

  final exitCode = await runner.run(args) ?? 0;
  exit(exitCode);
}

abstract class _SpecCommand extends Command<int> {
  _SpecCommand() {
    argParser.addOption(
      'spec',
      abbr: 's',
      help: 'Path to firepack.yaml',
      defaultsTo: 'firepack.yaml',
    );
  }

  Spec readSpec() {
    final path = argResults!['spec'] as String;
    final file = File(path);
    if (!file.existsSync()) {
      stderr.writeln('firepack: spec file not found: $path');
      throw _CliError(2);
    }
    return FirepackParser().parse(
      file.readAsStringSync(),
      sourceName: path,
    );
  }
}

class _LintCommand extends _SpecCommand {
  @override
  String get name => 'lint';
  @override
  String get description => 'Validates the spec — orphan refs, dup indexes, …';

  @override
  Future<int> run() async {
    final spec = readSpec();
    final issues = lint(spec);
    if (issues.isEmpty) {
      stdout.writeln('firepack lint: ok '
          '(${spec.collections.length} collections, '
          '${spec.collections.values.fold(0, (s, c) => s + c.fields.length)} fields)');
      return 0;
    }
    for (final issue in issues) {
      stdout.writeln(issue);
    }
    stdout.writeln('firepack lint: ${issues.length} issue(s)');
    return 1;
  }
}

class _VizCommand extends _SpecCommand {
  _VizCommand() {
    argParser.addOption(
      'out',
      abbr: 'o',
      help: 'Output Mermaid file (default: stdout)',
    );
  }

  @override
  String get name => 'viz';
  @override
  String get description =>
      'Renders the spec as a Mermaid erDiagram (paste into Markdown).';

  @override
  Future<int> run() async {
    final spec = readSpec();
    final mermaid = renderMermaid(spec);
    final outPath = argResults!['out'] as String?;
    if (outPath == null) {
      stdout.writeln(mermaid);
    } else {
      // When writing to .md, wrap in a Mermaid code-fence so GitHub
      // and most Markdown viewers render it inline.
      final body = outPath.toLowerCase().endsWith('.md')
          ? '<!-- GENERATED by firepack viz — re-run, do not hand-edit. -->\n\n'
              '```mermaid\n$mermaid```\n'
          : mermaid;
      File(outPath).writeAsStringSync(body);
      stdout.writeln('firepack viz: wrote $outPath '
          '(${body.length} chars)');
    }
    return 0;
  }
}

class _CliError implements Exception {
  final int exitCode;
  _CliError(this.exitCode);
}

/// Watches the spec file and re-runs the configured regen targets on
/// every save. Lives in this file (not lib/) because it's purely CLI:
/// reads the config, watches the FS, dispatches to the codegens.
///
/// Config: optional `firepack.config.yaml` next to the spec, listing
/// which targets to regenerate and where to write each output. Without
/// a config it falls back to writing `firestore.indexes.json` and
/// `firestore.rules` to the CWD — useful for ad-hoc spec hacking.
class _WatchCommand extends Command<int> {
  _WatchCommand() {
    argParser
      ..addOption(
        'spec',
        abbr: 's',
        help: 'Path to firepack.yaml',
        defaultsTo: 'firepack.yaml',
      )
      ..addOption(
        'config',
        abbr: 'c',
        help: 'Optional config YAML mapping targets → output paths. '
            'Defaults to <spec-dir>/firepack.config.yaml if present.',
      );
  }

  @override
  String get name => 'watch';

  @override
  String get description =>
      'Re-runs configured regen targets every time the spec file changes.';

  @override
  Future<int> run() async {
    final specPath = argResults!['spec'] as String;
    final specFile = File(specPath);
    if (!specFile.existsSync()) {
      stderr.writeln('firepack watch: spec not found: $specPath');
      return 2;
    }

    final configPath = argResults!['config'] as String? ??
        '${File(specPath).parent.path}/firepack.config.yaml';
    final targets = _loadWatchTargets(configPath);
    if (targets.isEmpty) {
      stdout.writeln(
        'firepack watch: no config — falling back to '
        'firestore.indexes.json + firestore.rules in CWD.',
      );
      targets.addAll([
        const _WatchTarget(target: 'indexes', out: 'firestore.indexes.json'),
        const _WatchTarget(target: 'rules', out: 'firestore.rules'),
      ]);
    } else {
      stdout.writeln(
        'firepack watch: ${targets.length} target(s) from $configPath',
      );
    }

    // First pass — write current outputs once so the project is in a
    // consistent state before the user even saves anything.
    _runAll(specPath, targets);

    final watcher = FileWatcher(specFile.absolute.path);
    stdout.writeln('firepack watch: watching $specPath  (Ctrl-C to exit)');
    await for (final event in watcher.events) {
      if (event.type == ChangeType.MODIFY || event.type == ChangeType.ADD) {
        stdout.writeln(
          '\nfirepack watch: spec changed at ${DateTime.now().toIso8601String()}',
        );
        _runAll(specPath, targets);
      }
    }
    return 0;
  }

  void _runAll(String specPath, List<_WatchTarget> targets) {
    final source = File(specPath).readAsStringSync();
    Spec spec;
    try {
      spec = FirepackParser().parse(source, sourceName: specPath);
    } catch (e) {
      stderr.writeln('firepack watch: spec parse error — $e');
      return;
    }

    for (final t in targets) {
      try {
        switch (t.target) {
          case 'indexes':
            File(t.out).writeAsStringSync(generateIndexesJson(spec));
            stdout.writeln('  ✓ indexes → ${t.out}');
          case 'rules':
            File(t.out).writeAsStringSync(generateRulesFile(spec));
            stdout.writeln('  ✓ rules → ${t.out}');
          case 'models':
            final dir = Directory(t.out);
            if (!dir.existsSync()) dir.createSync(recursive: true);
            final files = generateAllDartModels(spec, sourceFile: specPath);
            files.forEach((f, c) {
              if (t.collection != null &&
                  !_matchesCollection(f, t.collection!)) {
                return;
              }
              File('${t.out}/$f').writeAsStringSync(c);
            });
            stdout.writeln('  ✓ models → ${t.out}');
          case 'repos':
            final dir = Directory(t.out);
            if (!dir.existsSync()) dir.createSync(recursive: true);
            final files = generateAllRepositories(spec, sourceFile: specPath);
            files.forEach((f, c) {
              if (t.collection != null &&
                  !_matchesCollection(f, t.collection!)) {
                return;
              }
              File('${t.out}/$f').writeAsStringSync(c);
            });
            stdout.writeln('  ✓ repos → ${t.out}');
          case 'viz':
            final mermaid = renderMermaid(spec);
            final body = t.out.toLowerCase().endsWith('.md')
                ? '<!-- GENERATED by firepack viz — re-run, do not hand-edit. -->\n\n'
                    '```mermaid\n$mermaid```\n'
                : mermaid;
            File(t.out).writeAsStringSync(body);
            stdout.writeln('  ✓ viz → ${t.out}');
          case 'storage':
            final body = generateStoragePathsFile(spec, sourceFile: specPath);
            if (body == null) {
              stdout.writeln('  - storage skipped (no buckets in spec)');
            } else {
              File(t.out).writeAsStringSync(body);
              stdout.writeln('  ✓ storage → ${t.out}');
            }
          case 'paths':
            final body = generateFirestorePathsFile(spec, sourceFile: specPath);
            if (body == null) {
              stdout.writeln('  - paths skipped (no collections in spec)');
            } else {
              File(t.out).writeAsStringSync(body);
              stdout.writeln('  ✓ paths → ${t.out}');
            }
          case 'firestore_provider':
            File(t.out).writeAsStringSync(
              generateFirestoreProviderFile(sourceFile: specPath),
            );
            stdout.writeln('  ✓ firestore_provider → ${t.out}');
          default:
            stderr.writeln('  ✗ unknown target "${t.target}" — skipped');
        }
      } catch (e) {
        stderr.writeln('  ✗ ${t.target} → $e');
      }
    }
  }

  bool _matchesCollection(String fileName, String collection) {
    final stem =
        fileName.replaceAll('_repository.dart', '').replaceAll('.dart', '');
    return collection.toLowerCase().startsWith(stem.replaceAll('_', ''));
  }

  List<_WatchTarget> _loadWatchTargets(String path) {
    final f = File(path);
    if (!f.existsSync()) return [];
    final raw = loadYaml(f.readAsStringSync());
    if (raw is! YamlMap) return [];
    final targets = raw['targets'];
    if (targets is! YamlMap) return [];

    final out = <_WatchTarget>[];
    for (final entry in targets.entries) {
      final key = entry.key.toString();
      final body = entry.value;
      if (body is YamlMap) {
        out.add(_WatchTarget(
          target: key,
          out: body['out']?.toString() ?? _defaultOutFor(key),
          collection: body['collection']?.toString(),
        ));
      } else {
        out.add(_WatchTarget(target: key, out: _defaultOutFor(key)));
      }
    }
    return out;
  }

  String _defaultOutFor(String target) {
    switch (target) {
      case 'indexes':
        return 'firestore.indexes.json';
      case 'rules':
        return 'firestore.rules';
      case 'models':
        return 'lib/firepack/models';
      case 'repos':
        return 'lib/firepack/repositories';
      case 'storage':
        return 'lib/firepack/storage_paths.dart';
      case 'paths':
        return 'lib/firepack/paths.dart';
      case 'firestore_provider':
        return 'lib/firepack/firestore_provider.dart';
      default:
        return target;
    }
  }
}

class _WatchTarget {
  final String target;
  final String out;
  final String? collection;
  const _WatchTarget({
    required this.target,
    required this.out,
    this.collection,
  });
}

class _DiffCommand extends Command<int> {
  _DiffCommand() {
    argParser
      ..addOption(
        'old',
        help: 'Path to the OLD firepack.yaml (e.g. base branch).',
        mandatory: true,
      )
      ..addOption(
        'new',
        help: 'Path to the NEW firepack.yaml (e.g. PR branch).',
        mandatory: true,
      )
      ..addOption(
        'out',
        abbr: 'o',
        help: 'Where to write the Markdown report. "-" or omitted = stdout.',
      );
  }

  @override
  String get name => 'diff';

  @override
  String get description =>
      'Renders a Markdown diff between two firepack.yaml files — '
      'shape suitable for a PR comment.';

  @override
  Future<int> run() async {
    final oldPath = argResults!['old'] as String;
    final newPath = argResults!['new'] as String;
    final outPath = argResults!['out'] as String?;

    final oldFile = File(oldPath);
    final newFile = File(newPath);
    if (!oldFile.existsSync()) {
      stderr.writeln('firepack diff: --old file not found: $oldPath');
      return 2;
    }
    if (!newFile.existsSync()) {
      stderr.writeln('firepack diff: --new file not found: $newPath');
      return 2;
    }

    final oldSpec =
        FirepackParser().parse(oldFile.readAsStringSync(), sourceName: oldPath);
    final newSpec =
        FirepackParser().parse(newFile.readAsStringSync(), sourceName: newPath);
    final report = renderMarkdown(diffSpecs(oldSpec, newSpec));

    if (outPath == null || outPath == '-') {
      stdout.write(report);
    } else {
      File(outPath).writeAsStringSync(report);
      stdout.writeln('firepack diff: wrote $outPath '
          '(${report.length} chars)');
    }
    return 0;
  }
}

class _RegenCommand extends _SpecCommand {
  static const _supportedTargets = {
    'indexes',
    'rules',
    'models',
    'repos',
    'storage',
    'paths',
    'firestore_provider',
  };

  _RegenCommand() {
    argParser
      ..addOption(
        'target',
        abbr: 't',
        help: 'What to regenerate. Today: indexes, rules, models, '
            'repos, storage, paths.',
        allowed: [
          'indexes',
          'rules',
          'models',
          'repos',
          'storage',
          'paths',
          'firestore_provider'
        ],
        defaultsTo: 'indexes',
      )
      ..addOption(
        'out',
        abbr: 'o',
        help: 'Output file (single-file targets) or directory '
            '(multi-file targets like models). "-" for stdout '
            '(single-file targets only).',
      )
      ..addOption(
        'collection',
        abbr: 'c',
        help: 'For multi-file targets, restrict to one collection '
            '(e.g. --collection errorReports). Empty = all.',
      );
  }

  @override
  String get name => 'regen';

  @override
  String get description => 'Regenerates an artifact from the spec '
      '(indexes today, more targets coming via firepack ROADMAP).';

  @override
  Future<int> run() async {
    final target = argResults!['target'] as String;
    if (!_supportedTargets.contains(target)) {
      stderr.writeln(
        'firepack regen: target "$target" not yet implemented '
        '— see docs/ROADMAP.md.',
      );
      return 64; // EX_USAGE
    }

    final spec = readSpec();

    // Multi-file targets: models, repos.
    if (target == 'models' || target == 'repos') {
      final defaultOutDir = target == 'models'
          ? 'lib/firepack/models'
          : 'lib/firepack/repositories';
      final outDir = (argResults!['out'] as String?) ?? defaultOutDir;
      final filter = argResults!['collection'] as String?;
      final dir = Directory(outDir);
      if (!dir.existsSync()) dir.createSync(recursive: true);

      final specPath = argResults!['spec'] as String?;
      final files = target == 'models'
          ? generateAllDartModels(spec, sourceFile: specPath)
          : generateAllRepositories(spec, sourceFile: specPath);
      var written = 0;
      files.forEach((fileName, content) {
        if (filter != null && filter.isNotEmpty) {
          final inferredCollection = fileName
              .replaceAll('_repository.dart', '')
              .replaceAll('.dart', '');
          if (!filter
              .toLowerCase()
              .startsWith(inferredCollection.replaceAll('_', ''))) {
            return;
          }
        }
        final fullPath = '$outDir/$fileName';
        File(fullPath).writeAsStringSync(content);
        written++;
      });
      stdout.writeln('firepack regen $target: '
          'wrote $written file(s) into $outDir/');
      return 0;
    }

    // Single-file targets.
    String content;
    String defaultOut;
    switch (target) {
      case 'indexes':
        content = generateIndexesJson(spec);
        defaultOut = 'firestore.indexes.json';
      case 'rules':
        content = generateRulesFile(spec);
        defaultOut = 'firestore.rules';
      case 'storage':
        final body = generateStoragePathsFile(spec);
        if (body == null) {
          stdout.writeln('firepack regen storage: '
              'spec has no `storage:` block — nothing to generate.');
          return 0;
        }
        content = body;
        defaultOut = 'lib/firepack/storage_paths.dart';
      case 'paths':
        final body = generateFirestorePathsFile(spec);
        if (body == null) {
          stdout.writeln('firepack regen paths: '
              'spec has no collections — nothing to generate.');
          return 0;
        }
        content = body;
        defaultOut = 'lib/firepack/paths.dart';
      case 'firestore_provider':
        content = generateFirestoreProviderFile();
        defaultOut = 'lib/firepack/firestore_provider.dart';
      default:
        return 64;
    }

    final outPath = (argResults!['out'] as String?) ?? defaultOut;
    if (outPath == '-') {
      stdout.write(content);
    } else {
      File(outPath).writeAsStringSync(content);
      stdout.writeln('firepack regen: wrote $outPath '
          '(${content.length} chars)');
    }
    return 0;
  }
}
